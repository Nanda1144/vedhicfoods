import { z } from 'zod'

// ==========================================
// 1. RAZORPAY ORDER CREATION SCHEMAS
// ==========================================

export const createRazorpayOrderSchema = z.object({
  orderId: z
    .string()
    .uuid('Invalid order ID — must be a valid UUID')
    .describe('The Vedhic Foods internal order ID'),
})

export type CreateRazorpayOrderInput = z.infer<typeof createRazorpayOrderSchema>

// ==========================================
// 2. PAYMENT VERIFICATION SCHEMAS
// ==========================================

export const verifyPaymentSchema = z.object({
  razorpayOrderId: z
    .string()
    .min(1, 'Razorpay order ID is required')
    .describe('The order_XXX ID returned by Razorpay'),
  razorpayPaymentId: z
    .string()
    .min(1, 'Razorpay payment ID is required')
    .describe('The pay_XXX ID returned by Razorpay after payment'),
  razorpaySignature: z
    .string()
    .min(1, 'Razorpay signature is required')
    .describe('HMAC-SHA256 signature generated by Razorpay for verification'),
})

export type VerifyPaymentInput = z.infer<typeof verifyPaymentSchema>

// ==========================================
// 2b. ORDER-SCOPED PAYMENT CONFIRMATION
// ==========================================

/**
 * Payload accepted by `POST /api/v1/orders/:id/confirm-payment`.
 *
 * The identifiers are constrained to Razorpay's own `order_` / `pay_` formats so
 * that attacker-controlled strings can never reach the HMAC payload builder or
 * the database lookup with unbounded length.
 */
export const confirmPaymentSchema = z.object({
  razorpayOrderId: z
    .string()
    .trim()
    .regex(/^order_[A-Za-z0-9]{8,32}$/, 'Invalid Razorpay order ID'),
  razorpayPaymentId: z
    .string()
    .trim()
    .regex(/^pay_[A-Za-z0-9]{8,32}$/, 'Invalid Razorpay payment ID'),
  razorpaySignature: z
    .string()
    .trim()
    .regex(/^[a-f0-9]{64}$/i, 'Invalid Razorpay payment signature'),
})

export type ConfirmPaymentInput = z.infer<typeof confirmPaymentSchema>

/** Payload accepted by `POST /api/v1/orders/:id/payment-failed`. */
export const failPaymentSchema = z.object({
  reason: z.string().trim().max(200, 'Reason must not exceed 200 characters').optional(),
})

export type FailPaymentInput = z.infer<typeof failPaymentSchema>

// ==========================================
// 3. WEBHOOK EVENT SCHEMAS
// ==========================================

export const razorpayWebhookSchema = z.object({
  entity: z.string().optional(),
  account_id: z.string().optional(),
  event: z.string(),
  payload: z
    .object({
      payment: z
        .object({
          entity: z.object({
            id: z.string(),
            order_id: z.string(),
            amount: z.number(),
            currency: z.string(),
            status: z.string(),
            method: z.string().optional(),
            error_code: z.string().optional().nullable(),
            error_description: z.string().optional().nullable(),
          }),
        })
        .optional(),
    })
    .optional(),
})

export type RazorpayWebhookPayload = z.infer<typeof razorpayWebhookSchema>

// ==========================================
// 4. PAYMENT STATUS SCHEMA
// ==========================================

export const getPaymentStatusSchema = z.object({
  orderId: z.string().uuid('Invalid order ID'),
})

export type GetPaymentStatusInput = z.infer<typeof getPaymentStatusSchema>

// ==========================================
// 5. PAYMENT RESPONSE INTERFACES
// ==========================================

export interface RazorpayOrderResponse {
  /** Vedhic Foods internal order ID */
  orderId: string
  /** Vedhic Foods order number (VF-YYYY-NNNNNN) */
  orderNumber: string
  /** The Razorpay order object ID to pass to checkout SDK */
  razorpayOrderId: string
  /** Amount in paise (INR * 100) — authoritative, calculated by backend */
  amountInPaise: number
  /** Always INR */
  currency: string
  /** Public Razorpay key ID — safe to expose to frontend */
  keyId: string
  /** Customer name for pre-fill */
  customerName: string
  /** Customer email for pre-fill */
  customerEmail: string
  /** Customer phone for pre-fill */
  customerPhone: string
  /** Description shown in Razorpay checkout */
  description: string
}

export interface PaymentVerificationResponse {
  success: boolean
  message: string
  orderId: string
  orderNumber: string
  paymentId: string
  status: string
  verifiedAt: string
}

export interface PaymentStatusResponse {
  orderId: string
  orderNumber: string
  orderStatus: string
  paymentStatus: string
  paymentMethod: string
  amount: number
  currency: string
  razorpayOrderId: string | null
  razorpayPaymentId: string | null
  verifiedAt: string | null
  failureCode: string | null
  failureReason: string | null
  createdAt: string
  updatedAt: string
}
