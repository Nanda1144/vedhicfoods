function buildImages(seed: ProductSeed): string[] {
  return [0, 1, 2].map((index) =>
    placeholderImage({
      seed: `${seed.slug}-${index}`,
      variant: seed.variant,
      width: 900,
      height: 900,
    }),
  )
}

function buildSpecifications(seed: ProductSeed): ProductSpecification[] {
  return [
    { label: 'Net Weight', value: seed.unit },
    { label: 'Ingredients', value: seed.ingredients.join(', ') },
    { label: 'Shelf Life', value: SHELF_LIFE[seed.categorySlug] ?? 'Best within 6 months' },
    { label: 'Storage', value: 'Store in a cool, dry place in an airtight container.' },
    { label: 'Origin', value: 'Karnataka, India' },
    { label: 'Certification', value: 'India Organic · Jaivik Bharat' },
    { label: 'FSSAI Licence', value: '10024031000123' },
    { label: 'SKU', value: `VF-${seed.slug.toUpperCase().replace(/-/g, '').slice(0, 8)}` },
  ]
}

/**
 * Per-product reorder level. Scales with typical stock so fast-moving staples
 * (higher seeded stock) alert earlier in absolute units than slow movers.
 */
function lowStockThresholdFor(seed: ProductSeed): number {
  if (seed.stock <= 0) return 12
  return Math.min(40, Math.max(12, Math.round(seed.stock * 0.25)))
}

function toProduct(seed: ProductSeed, index: number): Product {
  return {
    id: `prd-${String(index + 1).padStart(3, '0')}`,
    slug: seed.slug,
    name: seed.name,
    categorySlug: seed.categorySlug,
    shortDescription: seed.short,
    description: DESCRIPTION[seed.categorySlug] ?? seed.short,
    price: seed.price,
    mrp: seed.mrp,
    currency: 'INR',
    unit: seed.unit,
    netWeight: seed.netWeight,
    images: buildImages(seed),
    tags: seed.tags,
    rating: seed.rating,
    reviewCount: seed.reviews,
    stock: seed.stock,
    lowStockThreshold: lowStockThresholdFor(seed),
    sku: `VF-${seed.slug.toUpperCase().replace(/-/g, '').slice(0, 8)}`,
    ingredients: seed.ingredients,
    allergens: ['May contain traces of tree nuts.'],
    shelfLife: SHELF_LIFE[seed.categorySlug] ?? 'Best within 6 months',
    storage: 'Store in a cool, dry place in an airtight container.',
    nutrition: NUTRITION_BY_CATEGORY[seed.categorySlug] ?? [],
    specifications: buildSpecifications(seed),
    isOrganic: true,
    isBestSeller: Boolean(seed.isBestSeller),
    isNew: Boolean(seed.isNew),
    isFeatured: Boolean(seed.isFeatured),
    createdAt: new Date(2026, 0, 1 + index * 4).toISOString(),
  }
}

